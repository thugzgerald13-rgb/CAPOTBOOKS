// Invoice PDF export + PH payment-link builder (Run 007 / T007).
// Parity: QuickBooks "Send invoice / download PDF / pay now" — we generate a
// branded PDF and a copyable payment message (GCash/Maya/bank) since no live
// payment gateway is connected yet.
import { jsPDF } from 'jspdf';
import type { BillingInvoice } from '../types';
import type { BusinessProfile } from '../types';

const money = (n: number) => `₱${Math.abs(n || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

function profileField(profile: BusinessProfile | undefined, key: string): string {
  if (!profile) return '';
  return String((profile as Record<string, any>)[key] ?? '').trim();
}

/** Branded A4 invoice PDF. Triggers a browser download. */
export function downloadInvoicePdf(inv: BillingInvoice, profile?: BusinessProfile) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 48;
  let y = 60;

  // Header band
  doc.setFillColor(99, 102, 241); // indigo-500
  doc.rect(0, 0, pageW, 90, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22); doc.setFont('helvetica', 'bold');
  doc.text(profileField(profile, 'tradeName') || 'CAPOT Books', margin, 40);
  doc.setFontSize(9); doc.setFont('helvetica', 'normal');
  const tin = profileField(profile, 'tin');
  if (tin) doc.text(`TIN: ${tin}`, margin, 56);
  doc.setFontSize(26); doc.setFont('helvetica', 'bold');
  doc.text('INVOICE', pageW - margin, 48, { align: 'right' });
  doc.setFontSize(10); doc.setFont('helvetica', 'normal');
  doc.text(`Invoice #: ${inv.invoiceNo}`, pageW - margin, 66, { align: 'right' });
  doc.text(`Date: ${inv.date}    Due: ${inv.dueDate}`, pageW - margin, 82, { align: 'right' });

  y = 130;
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(10); doc.setFont('helvetica', 'bold');
  doc.text('BILL TO', margin, y);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(11);
  y += 16;
  doc.text(inv.customerName, margin, y); y += 14;
  doc.text(`TIN: ${inv.customerTin}`, margin, y); y += 14;
  doc.text(inv.customerAddress, margin, y, { maxWidth: pageW - margin * 2 }); y += 24;

  // Line items table
  const tableX = margin, tableW = pageW - margin * 2;
  doc.setFillColor(241, 245, 249);
  doc.rect(tableX, y, tableW, 22, 'F');
  doc.setFontSize(9); doc.setFont('helvetica', 'bold'); doc.setTextColor(71, 85, 105);
  doc.text('DESCRIPTION', tableX + 10, y + 14);
  doc.text('AMOUNT', tableX + tableW - 10, y + 14, { align: 'right' });
  y += 22;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(30, 41, 59);
  doc.text(inv.description || 'Services rendered', tableX + 10, y + 16);
  doc.text(money(inv.amount), tableX + tableW - 10, y + 16, { align: 'right' });
  y += 30;
  doc.setDrawColor(226, 232, 240); doc.line(tableX, y, tableX + tableW, y); y += 16;

  // Totals
  const right = tableX + tableW - 10;
  doc.setFontSize(10);
  doc.text(`Subtotal (${inv.vatType})`, right - 140, y, { align: 'right' });
  doc.text(money(inv.netOfVat ?? inv.amount), right, y, { align: 'right' }); y += 16;
  if (inv.vatType === 'VATable') {
    doc.text('Output VAT (12%)', right - 140, y, { align: 'right' });
    doc.text(money(inv.outputTax ?? 0), right, y, { align: 'right' }); y += 16;
  }
  doc.setFont('helvetica', 'bold'); doc.setFontSize(12);
  doc.setFillColor(238, 242, 255); doc.rect(tableX, y - 10, tableW, 26, 'F');
  doc.setTextColor(79, 70, 229);
  doc.text('TOTAL DUE', right - 140, y + 7, { align: 'right' });
  doc.text(money(inv.amount), right, y + 7, { align: 'right' });
  y += 40;

  // Payment instructions (PH)
  doc.setTextColor(71, 85, 105); doc.setFontSize(9); doc.setFont('helvetica', 'bold');
  doc.text('PAYMENT INSTRUCTIONS', margin, y); y += 14;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
  const gcash = profileField(profile, 'gcashNumber') || 'GCash: (set in Business Profile)';
  const maya = profileField(profile, 'mayaNumber') || 'Maya: (set in Business Profile)';
  const bank = profileField(profile, 'bankDetails') || 'Bank transfer: (set in Business Profile)';
  doc.text(`Reference: ${inv.invoiceNo}`, margin, y); y += 12;
  doc.text(gcash, margin, y); y += 12;
  doc.text(maya, margin, y); y += 12;
  doc.text(bank, margin, y); y += 18;
  doc.setFontSize(8); doc.setTextColor(148, 163, 184);
  doc.text('Generated by CAPOT Books — Philippine accounting, BIR-ready.', margin, y);

  doc.save(`invoice-${String(inv.invoiceNo || inv.id).replace(/[^a-z0-9-_]+/gi, '-')}.pdf`);
}

/** Copyable payment message (what "payment link" copies to clipboard / email body). */
export function buildPaymentMessage(inv: BillingInvoice, profile?: BusinessProfile): string {
  const biz = profileField(profile, 'tradeName') || 'our business';
  const lines = [
    `Payment for Invoice ${inv.invoiceNo}`,
    `Amount due: ${money(inv.amount)}`,
    `Due date: ${inv.dueDate}`,
    ``,
    `Pay via:`,
    `- GCash: ${profileField(profile, 'gcashNumber') || '(merchant GCash number)'}`,
    `- Maya: ${profileField(profile, 'mayaNumber') || '(merchant Maya number)'}`,
    `- Bank: ${profileField(profile, 'bankDetails') || '(merchant bank details)'}`,
    `Reference: ${inv.invoiceNo} — ${inv.customerName}`,
    ``,
    `Thank you — ${biz}`,
  ];
  return lines.join('\n');
}

/** Copy payment message to clipboard. Returns true on success. */
export async function copyPaymentMessage(inv: BillingInvoice, profile?: BusinessProfile): Promise<boolean> {
  const text = buildPaymentMessage(inv, profile);
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Fallback: textarea + execCommand
    const ta = document.createElement('textarea');
    ta.value = text; document.body.appendChild(ta); ta.select();
    try { document.execCommand('copy'); return true; } catch { return false; }
    finally { ta.remove(); }
  }
}

/** Open the user's mail client with a pre-filled payment reminder. */
export function openPaymentReminderEmail(inv: BillingInvoice, profile?: BusinessProfile) {
  const subject = encodeURIComponent(`Reminder: Invoice ${inv.invoiceNo} — ${money(inv.amount)} due ${inv.dueDate}`);
  const body = encodeURIComponent(buildPaymentMessage(inv, profile));
  window.open(`mailto:?subject=${subject}&body=${body}`, '_blank');
}

