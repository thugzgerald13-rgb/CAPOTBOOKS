const hexToRgb = (hex: string): [number, number, number] => {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
};

function sellerAddress(profile: BusinessProfile | undefined): string {
  if (!profile) return '';
  const parts = [profileField(profile, 'substreet'), profileField(profile, 'street'),
    profileField(profile, 'barangay'), profileField(profile, 'district'),
    profileField(profile, 'city'), profileField(profile, 'zipCode')].filter(Boolean);
  return parts.join(', ');
}

function sellerContact(profile: BusinessProfile | undefined): string {
  if (!profile) return '';
  const parts = [profileField(profile, 'phone'), profileField(profile, 'email')].filter(Boolean);
  return parts.join('  ·  ');
}

/** Centered header band: trade name → address → contact → TIN. Document title
 *  is drawn by the caller BELOW the band (right side) to avoid overlap. */
function drawHeader(doc: jsPDF, tpl: InvoiceTemplate, profile: BusinessProfile | undefined, pageW: number, margin: number): number {
  const [r, g, b] = hexToRgb(tpl.primaryColor);
  const BAND_H = 115;
  doc.setFillColor(r, g, b);
  doc.rect(0, 0, pageW, BAND_H, 'F');
  doc.setTextColor(255, 255, 255);
  const cx = pageW / 2;
  const company = tpl.companyNameOverride || profileField(profile, 'tradeName') || profileField(profile, 'registeredName') || profileField(profile, 'name') || 'CAPOT Books';
  let y = 30;
  if (tpl.showLogo && tpl.logoDataUrl) {
    try { doc.addImage(tpl.logoDataUrl, 'PNG' as any, cx - 20, 14, 40, 28); y = 52; } catch { /* no logo */ }
  }
  doc.setFont(tpl.fontFamily || 'helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(company, cx, y, { align: 'center' });
  y += 16;
  doc.setFont(tpl.fontFamily || 'helvetica', 'normal');
  doc.setFontSize(8.5);
  if (tpl.tagline) { doc.text(tpl.tagline, cx, y, { align: 'center' }); y += 12; }
  if (tpl.showSellerAddress !== false) {
    const addr = sellerAddress(profile);
    if (addr) { doc.text(addr, cx, y, { align: 'center', maxWidth: pageW - margin * 2 }); y += 12; }
  }
  const contact = sellerContact(profile);
  if (contact) { doc.text(contact, cx, y, { align: 'center', maxWidth: pageW - margin * 2 }); y += 12; }
  if (tpl.showSellerTin !== false) {
    const tin = profileField(profile, 'tin');
    if (tin) { doc.text(`TIN: ${tin}`, cx, y, { align: 'center' }); y += 12; }
  }
  return BAND_H;
}

/** Right-aligned document title + meta, drawn below the header band. Returns y. */
function drawDocTitleMeta(doc: jsPDF, tpl: InvoiceTemplate, title: string, metaLines: string[], pageW: number, margin: number, startY: number): number {
  const [pr, pg, pb] = hexToRgb(tpl.primaryColor);
  doc.setTextColor(pr, pg, pb);
  doc.setFont(tpl.fontFamily || 'helvetica', 'bold');
  doc.setFontSize(18);
  let y = startY;
  doc.text(title, pageW - margin, y, { align: 'right' });
  y += 18;
  doc.setTextColor(71, 85, 105);
  doc.setFont(tpl.fontFamily || 'helvetica', 'normal');
  doc.setFontSize(9);
  for (const line of metaLines) {
    doc.text(line, pageW - margin, y, { align: 'right' });
    y += 13;
  }
  return y;
}

function drawFooter(doc: jsPDF, tpl: InvoiceTemplate, profile: BusinessProfile | undefined, y: number, margin: number, pageW: number) {
  doc.setTextColor(71, 85, 105); doc.setFontSize(9); doc.setFont(tpl.fontFamily || 'helvetica', 'bold');
  if (tpl.showPaymentInstructions !== false) {
    doc.text('PAYMENT INSTRUCTIONS', margin, y); y += 14;
    doc.setFont(tpl.fontFamily || 'helvetica', 'normal'); doc.setFontSize(9);
    if (tpl.paymentInstructions) {
      tpl.paymentInstructions.split('\n').forEach(line => { doc.text(line, margin, y); y += 12; });
    } else {
      doc.text(`GCash: ${profileField(profile, 'gcashNumber') || '(set in Business Profile)'}`, margin, y); y += 12;
      doc.text(`Maya: ${profileField(profile, 'mayaNumber') || '(set in Business Profile)'}`, margin, y); y += 12;
      doc.text(`Bank: ${profileField(profile, 'bankDetails') || '(set in Business Profile)'}`, margin, y); y += 12;
    }
    y += 6;
  }
  if (tpl.termsAndConditions) {
    doc.setFontSize(8); doc.setTextColor(100, 116, 139);
    doc.text('TERMS & CONDITIONS', margin, y); y += 11;
    tpl.termsAndConditions.split('\n').forEach(line => { doc.text(line, margin, y, { maxWidth: pageW - margin * 2 }); y += 10; });
    y += 4;
  }
  if (tpl.footerNote) { doc.setFontSize(8); doc.setTextColor(148, 163, 184); doc.text(tpl.footerNote, margin, y); }
}

/** Template-aware billing invoice PDF with service lines, discount and VAT breakdown. */
export function downloadTemplatedInvoicePdf(inv: BillingInvoice, profile: BusinessProfile | undefined, tpl: InvoiceTemplate) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 48;
  const tableX = margin;
  const tableW = pageW - margin * 2;
  const right = tableX + tableW - 8;
  const sourceLines: BillingInvoiceLineItem[] = Array.isArray(inv.lineItems) && inv.lineItems.length
    ? inv.lineItems
    : [{ id: 'fallback-line', description: inv.description || 'Services rendered', qty: 1, unitPrice: Number(inv.amount) || 0, amount: Number(inv.amount) || 0 }];
  const lineAmount = (line: any) => line.amount == null ? (Number(line.qty) || 0) * (Number(line.unitPrice) || 0) : Number(line.amount) || 0;
  const subtotal = sourceLines.reduce((sum, line) => sum + lineAmount(line), 0);
  const discountPercent = Math.max(0, Number(inv.discountPercent) || 0);
  const discountAmount = Math.max(0, subtotal - Number(inv.amount || 0));
  let y = drawHeader(doc, tpl, profile, pageW, margin) + 22;
  const titleBottom = drawDocTitleMeta(doc, tpl, tpl.documentTitle || 'INVOICE', [`Bill No.: ${inv.invoiceNo}`, `Date: ${inv.date}    Due: ${inv.dueDate}`], pageW, margin, y + 2);

  // Buyer block shares the title row horizontally, then content continues below both.
  let buyerY = y + 2;
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(10); doc.setFont(tpl.fontFamily || 'helvetica', 'bold');
  doc.text('BILL TO', margin, buyerY); buyerY += 16;
  doc.setFont(tpl.fontFamily || 'helvetica', 'normal'); doc.setFontSize(10.5);
  doc.text(inv.customerName || '', margin, buyerY); buyerY += 13;
  if (tpl.showBuyerTin && inv.customerTin) { doc.text(`TIN: ${inv.customerTin}`, margin, buyerY); buyerY += 13; }
  if (tpl.showBuyerAddress && inv.customerAddress) {
    const addressLines = doc.splitTextToSize(inv.customerAddress, tableW * 0.55);
    doc.text(addressLines, margin, buyerY);
    buyerY += addressLines.length * 12 + 3;
  }
  if (inv.customerEmail) { doc.text(inv.customerEmail, margin, buyerY); buyerY += 13; }
  y = Math.max(titleBottom, buyerY) + 16;

  const descriptionX = tableX + 8;
  const natureBillingX = tableX + tableW * 0.56;
  const amountColumnRight = right;
  const drawTableHeader = () => {
    doc.setFillColor(241, 245, 249); doc.rect(tableX, y, tableW, 22, 'F');
    doc.setFontSize(8); doc.setFont(tpl.fontFamily || 'helvetica', 'bold'); doc.setTextColor(71, 85, 105);
    doc.text('DESCRIPTION', descriptionX, y + 14);
    doc.text('NATURE BILLING', natureBillingX, y + 14);
    doc.text('AMOUNT', amountColumnRight, y + 14, { align: 'right' });
    y += 22;
  };
  drawTableHeader();
  doc.setFont(tpl.fontFamily || 'helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(30, 41, 59);
  for (const line of sourceLines) {
    const description = String(line.description || '—');
    const natureBilling = line.natureBilling === 'Advances'
      ? `Advances - ${String(line.advanceAccountTitle || line.accountTitle || 'Account not linked')}`
      : 'Income';
    const descriptionLines = doc.splitTextToSize(description, tableW * 0.50 - 14);
    const natureLines = doc.splitTextToSize(natureBilling, tableW * 0.27 - 8);
    const rowH = Math.max(20, Math.max(descriptionLines.length, natureLines.length) * 11 + 8);
    if (y + rowH > pageH - 110) {
      doc.addPage();
      y = 52;
      drawTableHeader();
      doc.setFont(tpl.fontFamily || 'helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(30, 41, 59);
    }
    doc.text(descriptionLines, descriptionX, y + 13);
    doc.text(natureLines, natureBillingX, y + 13);
    const amount = line.amount == null ? (Number(line.qty) || 0) * (Number(line.unitPrice) || 0) : Number(line.amount) || 0;
    doc.text(money(amount), amountColumnRight, y + 13, { align: 'right' });
    y += rowH;
    doc.setDrawColor(226, 232, 240); doc.line(tableX, y, tableX + tableW, y);
  }
  y += 18;

  const totals = (label: string, value: number, bold = false) => {
    if (y > pageH - 130) { doc.addPage(); y = 60; }
    doc.setFont(tpl.fontFamily || 'helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(9.5); doc.setTextColor(51, 65, 85);
    doc.text(label, right - 155, y, { align: 'right' });
    doc.text(value < 0 ? `-${money(value)}` : money(value), right, y, { align: 'right' });
    y += 15;
  };
  if (tpl.showVatBreakdown !== false) {
    totals('Subtotal (VAT-inclusive)', subtotal);
    if (discountAmount > 0) totals(`Discount (${discountPercent.toFixed(2).replace(/\.00$/, '')}%)`, -discountAmount);
    if (inv.vatType === 'VATable') {
      totals('Net of VAT', Number(inv.netOfVat) || 0);
      totals('Output VAT (12%)', Number(inv.outputTax) || 0);
    } else {
      totals(inv.vatType === 'Zero-Rated' ? 'Zero-rated sales' : 'VAT-exempt sales', Number(inv.amount) || 0);
    }
  }
  const [sr, sg, sb] = hexToRgb(tpl.secondaryColor);
  doc.setFillColor(sr, sg, sb); doc.rect(tableX, y - 10, tableW, 27, 'F');
  const [pr, pg, pb] = hexToRgb(tpl.primaryColor);
  doc.setFont(tpl.fontFamily || 'helvetica', 'bold'); doc.setFontSize(12); doc.setTextColor(pr, pg, pb);
  doc.text('TOTAL DUE', right - 155, y + 7, { align: 'right' });
  doc.text(money(inv.amount), right, y + 7, { align: 'right' });
  y += 40;
  drawFooter(doc, tpl, profile, y, margin, pageW);
  doc.save(`invoice-${String(inv.invoiceNo || inv.id).replace(/[^a-z0-9-_]+/gi, '-')}.pdf`);
}

