export function defaultTemplateFor(docType: TemplateDocType): InvoiceTemplate {
  return BUILTIN_TEMPLATES.find(t => t.docType === docType) || BUILTIN_TEMPLATES[0];
}

// ---------------------------------------------------------------------------
// CRUD — custom templates per client (localStorage; syncs to server optional)
// ---------------------------------------------------------------------------
export function listTemplates(clientId: string): InvoiceTemplate[] {
  const custom: InvoiceTemplate[] = JSON.parse(localStorage.getItem(STORAGE_KEY(clientId)) || '[]');
  return [...BUILTIN_TEMPLATES, ...custom];
}

export function listTemplatesFor(clientId: string, docType: TemplateDocType): InvoiceTemplate[] {
  return listTemplates(clientId).filter(t => t.docType === docType);
}

export function getTemplate(clientId: string, templateId: string | undefined): InvoiceTemplate {
  if (!templateId) return BUILTIN_TEMPLATES[0];
  return listTemplates(clientId).find(t => t.id === templateId) || BUILTIN_TEMPLATES[0];
}

export function saveTemplate(clientId: string, tpl: InvoiceTemplate): InvoiceTemplate[] {
  const key = STORAGE_KEY(clientId);
  const custom: InvoiceTemplate[] = JSON.parse(localStorage.getItem(key) || '[]');
  const idx = custom.findIndex(t => t.id === tpl.id);
  const withTs = { ...tpl, updatedAt: now() };
  if (idx >= 0) custom[idx] = withTs; else custom.push({ ...withTs, createdAt: now() });
  localStorage.setItem(key, JSON.stringify(custom));
  return listTemplates(clientId);
}

export function deleteTemplate(clientId: string, templateId: string): InvoiceTemplate[] {
  const key = STORAGE_KEY(clientId);
  const custom: InvoiceTemplate[] = JSON.parse(localStorage.getItem(key) || '[]')
    .filter(t => t.id !== templateId && !t.builtin);
  localStorage.setItem(key, JSON.stringify(custom));
  return listTemplates(clientId);
}

export function blankTemplate(docType: TemplateDocType, name: string): InvoiceTemplate {
  const base = defaultTemplateFor(docType);
  return {
    ...base,
    id: `tpl-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`,
    name, docType, builtin: false,
    createdAt: now(), updatedAt: now(),
  };
}
