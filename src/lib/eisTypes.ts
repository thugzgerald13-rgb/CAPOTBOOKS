// eisTypes.ts — BIR Electronic Invoicing System (EIS) domain types.
//
// Implements the BIR e-invoice JSON File Format v2.01 (CAS / CRM-POS schemas),
// the transmission lifecycle, and EIS certification / Permit-to-Issue (PTI)
// settings. Reference: https://bir-eis.ph/ and RMC No. 98-2026 (22 Sep 2026).
//
// Rules encoded here (RMC 98-2026, RR 11-2025 as amended by RR 26-2025):
//   * ISSUANCE mandate (NIRC s.237) — due 31 December 2026 for covered
//     taxpayers: issue structured, system-generated e-invoices to buyers.
//   * SALES REPORTING (NIRC s.237-A) — separate and distinct; applies only
//     once the BIR issues implementing rules. A Permit to Transmit (PTT) is
//     required only upon the Commissioner's directive.
//   * Gating: Permit to Issue (PTI) Electronic Invoice before the FIRST
//     e-invoice; EIS Certification within 6 months of the PTI (5 mandatory
//     tests, 7 with API callback) or the PTI may be revoked.
//   * Structured JSON only — PDFs/scans and invoices made in Word/Excel/
//     Google Docs/Sheets are NOT e-invoices.
//   * Valid e-invoice test (RMC 98-2026 IV.4): (a) generated by a registered/
//     approved/accredited system in structured format; (b) delivered to buyer
//     electronically (email, online viewing, QR, mobile app, web platform);
//     (c) data extractable & transmittable to BIR.
//   * Buyer TIN/name/address required for sales above PHP 1,000; walk-in
//     buyers use TIN 000000000 / "WALK-IN CUSTOMER".
//   * Every invoice is signed (JWS, RS256) then encrypted (AES-256-GCM).
//   * Submissions carry an HMAC-SHA256 request signature.
//   * 1–100 invoices per submission; reporting window (when operative) is
//     within 3 calendar days of invoice issuance.
//   * EisUniqueId is exactly 24 characters.
//   * Micro taxpayers (gross sales < PHP 3,000,000/yr) are EXEMPT from the
//     mandate and may adopt e-invoicing voluntarily.

// ---------------------------------------------------------------------------
// EIS v2.01 code enumerations
// ---------------------------------------------------------------------------

/** Document type. Under the EOPT Act the invoice is the primary sales document. */
export type EisDocType =
  | 'SI'   // Sales Invoice (goods or services, VAT or Non-VAT)
  | 'OR'   // Official Receipt (payment collection)
  | 'DR'   // Debit Note
  | 'CR';  // Credit Note

/** Transaction class. */
export type EisTransClass =
  | '1'  // Local sale / domestic
  | '2'  // Export sale
  | '3'  // Foreign currency denominated sale
  | '4'; // Special / exempt entity sale (e.g. government)

/** Correction indicator. */
export type EisCorrectionCd =
  | '0'  // Original document
  | '1'  // Replacement (re-issued)
  | '2'; // Cancellation

/** Per-line VAT treatment. */
export type EisTaxType =
  | 'V'  // Vatable (12%)
  | 'Z'  // Zero-rated
  | 'E'  // VAT-exempt
  | 'S'; // Services subject to percentage tax (non-VAT)

export const EIS_VAT_RATE = 0.12;
/** Issuance threshold (EOPT Act, NIRC s.237): an invoice is required for each
 *  sale of PHP 500 or more (daily aggregate below that; VAT-registered persons
 *  invoice EVERY sale regardless of amount). Adjusted for inflation every 3 yrs. */
export const EIS_ISSUANCE_THRESHOLD_PHP = 500;
/** Buyer details (TIN, name, address) required on the invoice for sales
 *  above this amount (RR 7-2024). Below it, walk-in coding is acceptable. */
export const EIS_BUYER_DETAIL_THRESHOLD_PHP = 1000;
/** Micro-taxpayer exemption threshold (gross sales/receipts < PHP 3M/yr):
 *  exempt from the mandatory e-invoicing mandate; may adopt voluntarily. */
export const EIS_MICRO_EXEMPTION_THRESHOLD_PHP = 3_000_000;
/** EIS Certification must be secured within this many months of PTI issuance,
 *  otherwise the PTI may be revoked (RMC 98-2026). */
export const EIS_CERTIFICATION_WINDOW_MONTHS = 6;
/** Covered-taxpayer categories (Wave 1, RR 11-2025 §3(A) as amended). */
export type EisCoveredCategory =
  | 'ecommerce'        // e-commerce / internet-transaction taxpayer (S/M/L)
  | 'lts'              // Large Taxpayers Service (LTS)
  | 'eopt-large'       // Large taxpayer under EOPT Act RA 11976 / RR 8-2024
  | 'cas-cba-software' // CAS, CBA-with-e-invoicing, or invoicing-software user
  | 'exporter-cas'     // Exporter / incentive RBE using CAS/CBA/invoicing sw
  | 'commissioner'     // Other taxpayers as required by the Commissioner
  | 'micro-exempt'     // Micro taxpayer (<PHP3M) — exempt, voluntary only
  | 'deferred';        // Exporters/RBEs/POS outside CAS group — wait for RR
/** How the e-invoice is delivered to the buyer (RMC 98-2026 IV.4(b)). One of
 *  these electronic delivery methods is REQUIRED for a valid e-invoice; a
 *  printed copy is allowed only where electronic delivery is impracticable,
 *  provided the invoice was generated (and can be issued) electronically. */
export type EisDeliveryMethod =
  | 'email' | 'online_viewing' | 'qr_code' | 'mobile_app' | 'web_platform' | 'printed_copy';
/** EIS Certification test results (5 mandatory, 7 with API callback). */
export interface EisCertificationTests {
  authentication: boolean;
  invoiceIssuance: boolean;
  inquiryResult: boolean;
  errorHandling: boolean;
  batchTransmission: boolean;
  apiCallback?: boolean;   // optional 6th
  offlineResubmission?: boolean; // optional 7th
  completedAt?: string;
}

// ---------------------------------------------------------------------------
// EIS v2.01 invoice JSON (CAS schema — used by CAS/CBA/invoicing software)
// ---------------------------------------------------------------------------

export interface EisSeller {
  TIN: string;            // 9 digits, no dashes
  BranchCode: string;     // 5 digits (00000 = head office)
  RegisteredName: string;
  TradeName?: string;     // "doing business as" name, shown on invoice
  VatRegistered: boolean; // VAT-registered persons must invoice every sale
  Email?: string;
  Phone?: string;
  // ATP (Authority to Print) / permit series range — for system-generated
  // invoices the serial number must fall within the registered series.
  PermitNumber?: string;
  SeriesStart?: string;
  SeriesEnd?: string;
  Address: {
    UnitFloorBuilding?: string;
    Street?: string;
    Barangay?: string;
    District?: string;
    City: string;
    Province?: string;
    ZipCode?: string;
  };
}

export interface EisBuyer {
  TIN: string;            // 9 digits; "000000000" for walk-in / cash sale
  BranchCode: string;     // 5 digits; "00000" if unknown
  Name: string;           // "WALK-IN CUSTOMER" if unknown
  Address?: string;
}

export interface EisLineItem {
  NBSeq: number;          // line number, 1-based
  ItemCode?: string;
  ItemDesc: string;
  Qty: number;
  UnitOfMeasure?: string;
  UnitCost: number;
  Amount: number;         // Qty * UnitCost (gross of VAT for vatable lines)
  TaxType: EisTaxType;
  TaxRate: number;        // 0.12 / 0 / 0
  Discount?: { Indicator: string; Amount: number };
}

export interface EisWithholdingTax {
  ATC: string;            // ATC code, e.g. WI 010 / WC 160
  Description?: string;
  Rate: number;           // e.g. 0.01, 0.02, 0.05
  Amount: number;         // tax withheld (deducted from amount due)
}
export interface EisSummary {
  TotalVatableSales: number;
  TotalZeroRatedSales: number;
  TotalExemptSales: number;
  TotalDiscount?: number;
  TotalVAT: number;               // 12% of vatable (net of discount)
  TotalAmountNetOfVAT?: number;
  AmountDue: number;              // grand total = vatable + zero + exempt + VAT
  WithholdingTax?: number;        // total withheld (sum of lines below)
  WithholdingTaxes?: EisWithholdingTax[];
  NetPayable?: number;            // AmountDue − WithholdingTax
  Currency: 'PHP' | string;
}

export interface EisInvoiceJson {
  EisUniqueId: string;     // 24 chars: TIN(9) + Branch(5) + YYYYMMDD(8) + Seq(2)
  DocType: EisDocType;
  TransClass: EisTransClass;
  CorrectionCd: EisCorrectionCd;
  OriginalEisUniqueId?: string; // when CorrectionCd = '1' or '2'
  IssueDate: string;       // YYYY-MM-DD
  IssueTime: string;       // HH:mm:ss
  InvoiceNumber: string;   // internal SI/OR number (ATP permit series)
  DocumentLabel?: string;  // "Invoice" / "Sales Invoice" / "Official Receipt"
  Seller: EisSeller;
  Buyer: EisBuyer;
  LineItems: EisLineItem[];
  Summary: EisSummary;
  PaymentTerms?: string;
  Remarks?: string;
  // How this e-invoice was delivered to the buyer (RMC 98-2026 IV.4(b)).
  // A valid e-invoice MUST be delivered by at least one electronic method.
  DeliveryMethod?: EisDeliveryMethod;
  DeliveredAt?: string;    // ISO timestamp of electronic delivery
  DeliveryReference?: string; // email message-id / QR token / view link
}

// ---------------------------------------------------------------------------
// Transmission lifecycle
// ---------------------------------------------------------------------------

export type EisTransmissionStatus =
  | 'draft'        // built, not yet queued
  | 'queued'       // waiting to be sent (within 3-day window)
  | 'submitted'    // POST accepted, awaiting per-invoice result
  | 'accepted'     // BIR inquiry returned ACC / success code
  | 'rejected'     // BIR returned an error code (fix + resend)
  | 'cancelled';   // CorrectionCd=2 sent

export interface EisTransmission {
  id: string;
  clientId: string;
  invoiceId: string;          // BillingInvoice.id or Sale.ref
  invoiceNumber: string;
  eisUniqueId: string;
  docType: EisDocType;
  issueDate: string;
  amountDue: number;
  status: EisTransmissionStatus;
  // Submission batch reference (one POST carries 1–100 invoices)
  batchId?: string;
  submittedAt?: string;
  // Per-invoice BIR result (from inquiry endpoint / callback)
  birAckCode?: string;        // e.g. ACC, SYN004, ERR002, ERR004
  birAckMessage?: string;
  birAckAt?: string;
  // Retry / audit
  attempts: number;
  lastError?: string;
  // Stored payloads (10-year retention requirement)
  invoiceJson?: EisInvoiceJson;
  jws?: string;
  createdAt: string;
  updatedAt: string;
}

// ---------------------------------------------------------------------------
// EIS certification / PTI settings (per taxpayer / client)
//
// Gating under RMC 98-2026:
//   1. PTI (Permit to Issue) Electronic Invoice — apply at your RDO / Large
//      Taxpayer Office BEFORE issuing any e-invoice. BIR evaluates within
//      20 working days. Distinct from CAS Permit to Use.
//   2. EIS Certification — pass 5 mandatory tests (7 with API callback) at
//      eis-cert.bir.gov.ph WITHIN 6 MONTHS of the PTI, or the PTI may be
//      revoked.
//   3. PTT (Permit to Transmit) — applies ONLY to the s.237-A electronic sales
//      reporting duty, "separate and distinct", not yet operative (Oct 2026).
// ---------------------------------------------------------------------------

export type EisEnvironment = 'sandbox' | 'production';

export interface EisSettings {
  clientId: string;
  enabled: boolean;
  environment: EisEnvironment;
  // Covered-taxpayer self-assessment (decides whether the mandate applies).
  coveredCategory: EisCoveredCategory;
  // From EIS Certification Portal (eis-cert.bir.gov.ph)
  applicationKey: string;             // Application Key (Settings page)
  eisCertificateNumber?: string;      // issued after sandbox tests pass
  permitToIssueNumber?: string;       // PTI — REQUIRED before first e-invoice
  permitToIssueDate?: string;         // PTI issue date (6-month cert clock)
  // PTT — for s.237-A sales reporting only; not yet operative (Oct 2026).
  permitToTransmitNumber?: string;
  certificationTests?: EisCertificationTests;
  taxpayerTin: string;                // 9 digits
  branchCode: string;                 // 5 digits, 00000 = HO
  systemType: 'CAS' | 'CRM/POS';      // decides which v2.01 schema variant
  // Default delivery method to the buyer (RMC 98-2026 IV.4(b)).
  defaultDeliveryMethod: EisDeliveryMethod;
  // Signing key pair (RS256). Private key is JWK, stored encrypted at rest.
  // In production these live server-side (Supabase Edge Function) and only
  // the public key + key id are kept in the browser.
  signingKeyId?: string;
  publicKeyJwk?: JsonWebKey;
  privateKeyJwkEncrypted?: string;    // browser-mode only, passphrase-protected
  // Server transmit proxy (recommended — BIR whitelists fixed server IPs)
  useEdgeProxy: boolean;
  // Whitelisted server IPs (informational — must match EIS portal entry)
  whitelistedIps?: string[];
  // Callback URL for BIR async result notifications (optional)
  callbackUrl?: string;
  updatedAt?: string;
}

